-- Two nullable columns the customer billing surface only ever reads. The staff
-- grant endpoint (in flight, not in this repo yet) writes them; without them a
-- customer reading "+500 · ADJUSTMENT" learns the amount and nothing about why
-- it arrived.
--
-- IF NOT EXISTS is deliberate, and is not what Prisma generated. The staff
-- admin slice adds these same two columns for its writer, in
-- `20260827120000_ledger_reference_and_note`. That name sorts BEFORE this one,
-- so a repository holding both applies theirs first and this one no-ops —
-- which is the case this guard is for.
--
-- It does NOT make the two safe in either order, and the guard here cannot:
-- if this migration reaches a database first, theirs is still pending, still
-- sorts earlier, and still runs an unguarded ADD COLUMN that fails on the
-- duplicate — halting every later migration behind it. Both files carry the
-- guard as of this change; if that one is ever regenerated by Prisma, the
-- ordering constraint comes back and this slice must not deploy ahead of it.
--
-- Nullable, no default, no backfill: this rewrites no rows and takes no long
-- lock on a populated table.
ALTER TABLE "CreditTransaction" ADD COLUMN IF NOT EXISTS "note" TEXT;
ALTER TABLE "CreditTransaction" ADD COLUMN IF NOT EXISTS "reference" TEXT;
